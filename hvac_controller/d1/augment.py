"""Direction 1, V2: more training scenarios, from the organisers' building generator and TMYx weather strips.

The hidden test set is 6 buildings from the same generator, at 5 stations that appear nowhere in training (the
organisers' paper, arXiv 2610.18511). So the training set adds generated buildings, each paired with strips of
stations drawn by climate:

- buildings: ``smart_buildings.run_floor_generator``, the first 60 seeds from 500 (training) and the first 6 from 900
  (held out) whose floor plan passes the generator's own zone-area check (it refuses seeds with a sliver zone under
  20 m2, e.g. 514). The check depends on the geometry, and the geometry on the seed only. Materials are stratified
  over the final seed list, so each list is generated by one fixed call, identical in every session;
- stations: the TMYx table (hvac_controller.weather), without the 6 shipped stations and Antarctica, with an annual
  mean temperature in [-10, 30) C, whole 5 K bins (the shipped ones span -2 fairbanks to 28 singapore; colder
  climates would dominate the loss with heating costs no test building is likely to face). A fixed tenth (by a hash of the station name) is held out and never trained on. The rest is
  stratified by annual mean temperature (5 K bins) x annual range (tertiles); each training building gets 3 strips
  from 3 different climate cells, each held-out building 2 from held-out stations;
- strips: 30 days from a Sunday 06:00 (as the shipped strips), week 0-47 of the station's year; convection
  coefficient estimated from the mean wind (weather.estimate_h);
- also held out: building_train_2 (the held-out shipped building) at minneapolis_1 and _5 (shipped presets of the
  one shipped station no training scenario uses).

``manifest`` picks the seeds and the strips and writes the list (deterministic), ``buildings`` the building YAMLs, and
``scenarios`` the weather presets and scenario folders of a shard of it. Run from the repository root: the generator
writes repo-relative paths.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import random
import tempfile
from pathlib import Path

import numpy as np

from hvac_controller import weather

TRAIN_FROM, N_TRAIN = 500, 60  # candidate seeds from 500, the first 60 valid ones
VAL_FROM, N_VAL = 900, 6
PER_TRAIN, PER_VAL = 3, 2
VAL_SHIPPED = (("building_train_2", "minneapolis_1"), ("building_train_2", "minneapolis_5"))
TAGS = ("gen_train", "gen_val", "shipped_building_new_station")
MEAN_RANGE = (-10.0, 30.0)  # annual mean temperature of usable stations, C, [lo, hi)


def held_out_station(stem: str) -> bool:
    return int(hashlib.sha256(stem.encode()).hexdigest()[:8], 16) % 10 == 0


def climate_cells(table: dict) -> tuple[dict, dict]:
    """Usable stations by climate cell (mean temperature bin, range tertile), for training and held out."""
    shipped = set(weather.SHIPPED_STEMS.values())
    rows = [r for r in table.values() if MEAN_RANGE[0] <= float(r["temp_mean"]) < MEAN_RANGE[1]
            and r["stem"] not in shipped and r["country"] != "ATA"]
    spans = np.array([float(r["temp_max"]) - float(r["temp_min"]) for r in rows])
    edges = np.quantile(spans, [1 / 3, 2 / 3])
    train, val = {}, {}
    for r, span in zip(rows, spans):
        cell = (int(np.floor(float(r["temp_mean"]) / 5.0)), int(np.searchsorted(edges, span)))
        (val if held_out_station(r["stem"]) else train).setdefault(cell, []).append(r["stem"])
    return ({c: sorted(v) for c, v in sorted(train.items())}, {c: sorted(v) for c, v in sorted(val.items())})


def _strips(cells: dict, n: int, rng) -> list[str]:
    """n stations from n different cells (uniform over cells, then over the cell's stations)."""
    keys = list(cells)
    chosen = rng.choice(len(keys), size=n, replace=False)
    return [cells[keys[i]][rng.integers(len(cells[keys[i]]))] for i in chosen]


def valid_seeds(start: int, n: int) -> list[int]:
    """The first n seeds from start whose floor plan passes the generator's zone-area check (as
    generate_scenario_from_config seeds and runs it)."""
    from smart_buildings import run_floor_generator
    from smart_buildings.smart_control.utils import scenario_generator as sg

    out, seed = [], start
    with tempfile.TemporaryDirectory() as tmp:
        while len(out) < n:
            batch = list(range(seed, seed + 2 * (n - len(out))))
            run_floor_generator.main(["--seeds", *map(str, batch), "--output-dir", tmp, "--no-pdf", "--no-materials"])
            for s in batch:
                config = sg.load_building_config(str(Path(tmp) / f"building_{s:04d}.yaml"))
                random.seed(config.seed)
                np.random.seed(config.seed)
                generator = sg._create_floor_plan_generator(config.floor_plan)
                generator.generate()
                try:
                    sg._check_generated_zone_areas(generator, sg.CONTROL_VOLUME_CM, config.seed)
                except ValueError as e:
                    print(f"seed {s} refused: {str(e)[:120]}")
                    continue
                if len(out) < n:
                    out.append(s)
            seed = batch[-1] + 1
    return out


def pick_strips(table: dict, train_seeds: list[int], val_seeds: list[int], seed: int = 0) -> list[dict]:
    """The manifest: one entry per scenario (building, weather name, label, tag, and for TMYx strips the station,
    start and convection coefficient)."""
    rng = np.random.default_rng(seed)
    train_cells, val_cells = climate_cells(table)
    out = []
    for seeds, cells, per, tag in ((train_seeds, train_cells, PER_TRAIN, "gen_train"),
                                   (val_seeds, val_cells, PER_VAL, "gen_val")):
        for b in seeds:
            for stem in _strips(cells, per, rng):
                start = np.datetime64("2023-01-01T06:00") + np.timedelta64(7 * int(rng.integers(0, 48)), "D")
                out.append({"building": f"building_{b:04d}", "stem": stem,
                            "start": str(start).replace("T", " ")[:16],
                            "h": round(weather.estimate_h(float(table[stem]["wind_mean_ms"])), 1), "tag": tag})
    for i, e in enumerate(out):
        e["weather"] = f"x{i:03d}"
    out += [{"building": b, "weather": w, "tag": "shipped_building_new_station"} for b, w in VAL_SHIPPED]
    for e in out:
        e["label"] = f"{e['building']}__{e['weather']}"
    return out


def make_buildings(entries: list[dict], out_dir: Path) -> list[Path]:
    """The manifest's generated buildings' YAMLs (the training and held-out seed lists, one call each)."""
    from smart_buildings import run_floor_generator

    paths = []
    for tag in ("gen_train", "gen_val"):
        seeds = sorted({int(e["building"].split("_")[1]) for e in entries if e["tag"] == tag})
        run_floor_generator.main(["--seeds", *map(str, seeds), "--output-dir", str(out_dir), "--no-pdf"])
        paths += [out_dir / f"building_{s:04d}.yaml" for s in seeds]
    return paths


def write_scenarios(entries: list[dict], packed: Path | None) -> list[Path]:
    """Weather presets (unless already there) and scenario folders; returns the config.gin paths. From the repo root."""
    from smart_buildings.smart_control.utils.scenario_generator import (generate_scenario_from_config,
                                                                        load_scenario_from_parts)

    wdir, bdir = Path("smart_buildings/weather"), Path("smart_buildings/buildings")
    pk = weather.Packed(packed) if packed else None
    out = []
    for e in entries:
        preset = wdir / f"{e['weather']}.yaml"
        if "stem" in e and not preset.exists():
            weather.write_preset(pk, e["stem"], wdir, e["start"], h=e["h"], name=e["weather"])
        config = load_scenario_from_parts(str(bdir / f"{e['building']}.yaml"), str(preset),
                                          output_base_dir="smart_buildings/training_scenarios")
        generate_scenario_from_config(config)
        out.append(Path("smart_buildings/training_scenarios") / e["building"] / e["weather"] / "config.gin")
    return out


def _summary(entries: list[dict], table: dict) -> str:
    gen = [e for e in entries if "stem" in e]
    lines = [f"{len(entries)} scenarios: " + ", ".join(f"{t} {sum(e['tag'] == t for e in entries)}" for t in TAGS),
             f"{len({e['stem'] for e in gen})} stations; held out by hash: "
             f"{len({e['stem'] for e in gen if e['tag'] == 'gen_val'})}"]
    t = np.array([float(table[e["stem"]]["temp_mean"]) for e in gen])
    lines.append("annual mean temperature (C) of the strips' stations: " + " ".join(
        f"{lo:+.0f}..{lo + 5:+.0f}:{int(((t >= lo) & (t < lo + 5)).sum())}" for lo in range(-20, 35, 5)))
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    m = sub.add_parser("manifest")
    m.add_argument("out", type=Path)
    m.add_argument("--packed", type=Path, required=True, help="the packed TMYx data (folder or data.zip)")
    m.add_argument("--seed", type=int, default=0)
    bl = sub.add_parser("buildings")
    bl.add_argument("manifest", type=Path)
    s = sub.add_parser("scenarios")
    s.add_argument("manifest", type=Path)
    s.add_argument("--packed", type=Path, help="needed unless every preset is already in smart_buildings/weather")
    s.add_argument("--tags", default=",".join(TAGS))
    s.add_argument("--shard", type=int, default=0)
    s.add_argument("--shards", type=int, default=1)
    s.add_argument("--out", type=Path, help="write the shard's entries (with their config paths) here")
    a = ap.parse_args()
    if not Path("smart_buildings/weather").is_dir():
        raise SystemExit("run from the repository root")
    if a.cmd == "manifest":
        pk = weather.Packed(a.packed)
        entries = pick_strips(pk.table, valid_seeds(TRAIN_FROM, N_TRAIN), valid_seeds(VAL_FROM, N_VAL), a.seed)
        a.out.write_text(json.dumps(entries, indent=1))
        print(_summary(entries, pk.table))
    elif a.cmd == "buildings":
        paths = make_buildings(json.loads(a.manifest.read_text()), Path("smart_buildings/buildings"))
        print(f"{len(paths)} building YAMLs")
    else:
        tags = set(a.tags.split(","))
        entries = sorted((e for e in json.loads(a.manifest.read_text()) if e["tag"] in tags), key=lambda e: e["label"])
        mine = entries[a.shard::a.shards]
        configs = write_scenarios(mine, a.packed)
        for e, c in zip(mine, configs):
            e["config"] = str(c)
        if a.out:
            a.out.write_text(json.dumps(mine, indent=1))
        print(f"shard {a.shard}/{a.shards}: {len(mine)} scenarios written, cwd {os.getcwd()}")


if __name__ == "__main__":
    main()
